// Provisioning must remain byte-compatible with the native admission owner.
package competitionagent

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"strings"
	"testing"
)

// Exercise the actual production renderer and admission document checker.
func TestRuntimeProvisioningDocumentsMatchNativeAdmission(t *testing.T) {
	fixture := runtimeProvisioningTest(t)
	plan, err := RenderRuntimeProvisioningDocuments(fixture.boundary, fixture.scope, fixture.settings)
	if err != nil {
		t.Fatal(err)
	}
	if plan.RuntimeQualified || plan.Kind != "runtime-resource-provisioning-documents/v1" {
		t.Fatal("rendering claimed native qualification")
	}
	if fixture.boundary.EngineConfig.Sha256 != "" || fixture.boundary.ContainerdConfig.Sha256 != "" || fixture.boundary.NetworkPolicy.Sha256 != "" {
		t.Fatal("rendering modified caller metadata")
	}
	if plan.Boundary.EngineConfig.Sha256 != plan.Engine.Sha256 || plan.Boundary.ContainerdConfig.Sha256 != plan.Containerd.Sha256 || plan.Boundary.NetworkPolicy.Sha256 != plan.Network.Sha256 {
		t.Fatal("completed metadata did not bind actual generated bytes")
	}
	if err := validateRuntimeBoundaryDocuments(fixture.boundary, plan.Engine.Content, plan.Containerd.Content, plan.Network.Content, fixture.settings); err != nil {
		t.Fatal(err)
	}
	content, err := json.Marshal(plan)
	if err != nil {
		t.Fatal(err)
	}
	var replay RuntimeProvisioningDocuments
	if err := json.Unmarshal(content, &replay); err != nil {
		t.Fatal(err)
	}
	for _, document := range []RuntimeProvisioningDocument{replay.Engine, replay.Containerd, replay.Network} {
		digest := sha256.Sum256(document.Content)
		if document.Sha256 != hex.EncodeToString(digest[:]) {
			t.Fatal("document lost its exact content identity")
		}
	}
	if !bytes.Equal(plan.Containerd.Content, replay.Containerd.Content) || !bytes.Equal(plan.Network.Content, replay.Network.Content) {
		t.Fatal("JSON transport normalized closed document bytes")
	}
}

// The renderer cannot make a global/user Docker socket appear admissible.
func TestRuntimeProvisioningDocumentsRejectAuthorityOverlap(t *testing.T) {
	fixture := runtimeProvisioningTest(t)
	fixture.boundary.PrivateSocketPath = "/var/run/docker.sock"
	if plan, err := RenderRuntimeProvisioningDocuments(fixture.boundary, fixture.scope, fixture.settings); err == nil || plan != nil {
		t.Fatal("rendered unsafe engine authority")
	}
}

// Invalid owner-local bounds refuse before allocating any plan document.
func TestRuntimeProvisioningDocumentsRejectUnboundedSettings(t *testing.T) {
	fixture := runtimeProvisioningTest(t)
	fixture.settings.CommandTimeout = 0
	if plan, err := RenderRuntimeProvisioningDocuments(fixture.boundary, fixture.scope, fixture.settings); err == nil || plan != nil {
		t.Fatal("rendered unbounded provisioning settings")
	}
}

// Only generated document hashes are unknown in a prospective plan.
func runtimeProvisioningTest(t *testing.T) *runtimeBoundaryTest {
	t.Helper()
	fixture := newRuntimeBoundaryTest(t)
	fixture.boundary.EngineConfig.Sha256 = ""
	fixture.boundary.ContainerdConfig.Sha256 = ""
	fixture.boundary.NetworkPolicy.Sha256 = ""
	return fixture
}

// A renderer cannot silently rewrite a previously declared immutable document.
func TestRuntimeProvisioningDocumentsRejectChangedDeclaredDigest(t *testing.T) {
	fixture := runtimeProvisioningTest(t)
	fixture.boundary.EngineConfig.Sha256 = strings.Repeat("f", 64)
	if plan, err := RenderRuntimeProvisioningDocuments(fixture.boundary, fixture.scope, fixture.settings); err == nil || plan != nil {
		t.Fatal("changed declared digest was silently rebound")
	}
}
