var ErrProberShardRetired = errors.New("probe shard execution is retired")

// An epoch is minted for one task execution (task.ExecutionIdentityFromContext)
// and leads with its creation millisecond. One older than this belongs to an
// execution that ended long ago, so it cannot begin a shard: the retention
// drops a closed epoch's registry row with its generation, and that row is
// what fences a replay.
const proberShardEpochMaxAge = 24 * time.Hour

// These IDs are generated by the task owner, never accepted from an API payer.
// Each execution gets a different network, including a retry of the same task.
type ProberShardKey struct {
	TaskId     server.Id
	Epoch      server.Id
	ShardIndex int
	ShardCount int
}

type ProberShardOwner struct {
	Key              ProberShardKey
	NetworkId        server.Id
	UserId           server.Id
	ClientId         server.Id
	DeviceId         server.Id
	BalanceId        server.Id
	State            string
	Deadline         time.Time
	RetiredClientIds []server.Id
}

const proberShardColumns = `task_id, epoch, shard_index, shard_count, network_id, user_id, client_id, device_id, balance_id, state, deadline, retired_client_ids`

func scanProberShard(row interface{ Scan(...any) error }) (*ProberShardOwner, error) {
	owner := &ProberShardOwner{}
	err := row.Scan(&owner.Key.TaskId, &owner.Key.Epoch, &owner.Key.ShardIndex, &owner.Key.ShardCount,
		&owner.NetworkId, &owner.UserId, &owner.ClientId, &owner.DeviceId, &owner.BalanceId, &owner.State, &owner.Deadline, &owner.RetiredClientIds)
	return owner, err
}

// BeginProberShard commits creation and its ownership record together. A lost
// reply can replay this epoch; a process crash cannot leave an untracked account.
// There is exactly one funded row in this private network and no global top-up.
func BeginProberShard(ctx context.Context, key ProberShardKey, credit ByteCount, lifetime time.Duration) (owner *ProberShardOwner, returnErr error) {
	if key.TaskId == (server.Id{}) || key.Epoch == (server.Id{}) || key.ShardIndex < 0 || key.ShardCount <= key.ShardIndex || key.ShardCount > 256 || credit <= 0 || lifetime <= 0 || lifetime > 24*time.Hour {
		return nil, errors.New("invalid probe shard ownership or funding")
	}
	return server.HandleError2(func() (*ProberShardOwner, error) {
		server.Tx(ctx, func(tx server.PgTx) {
			owner, returnErr = nil, nil
			// Stable shard admission orders geometry changes and task retries.
			server.RaisePgResult(tx.Exec(ctx, `SELECT pg_advisory_xact_lock(192847301, $1)`, key.ShardIndex))
			var now time.Time
			server.Raise(tx.QueryRow(ctx, `SELECT clock_timestamp() AT TIME ZONE 'UTC'`).Scan(&now))
			if proberShardEpochMaxAge < now.Sub(server.ContractIdTime(key.Epoch)) {
				returnErr = ErrProberShardRetired
				return
			}
			rows, err := tx.Query(ctx, `SELECT `+proberShardColumns+` FROM prober_shard_run WHERE task_id=$1 AND epoch=$2 FOR UPDATE`, key.TaskId, key.Epoch)
			server.WithPgResult(rows, err, func() {
				if rows.Next() {
					owner, err = scanProberShard(rows)
					server.Raise(err)
				}
			})
			if owner != nil {
				if owner.Key != key || owner.State != "active" || !now.Before(owner.Deadline) {
					returnErr = ErrProberShardRetired
				}
				return
			}
			// A new epoch must retire a previous owner before minting anything.
			var previous *ProberShardOwner
			rows, err = tx.Query(ctx, `SELECT `+proberShardColumns+` FROM prober_shard_run WHERE shard_index=$1 AND state='active' FOR UPDATE`, key.ShardIndex)
			server.WithPgResult(rows, err, func() {
				if rows.Next() {
					previous, err = scanProberShard(rows)
					server.Raise(err)
				}
			})
			if previous != nil {
				server.Raise(drainProberShardInTx(ctx, tx, previous))
			}
			// The replacement grant id is fresh and unpublished until commit;
			// only the previous owner's existing grant needs shared ownership.
			owner = &ProberShardOwner{Key: key, NetworkId: server.NewId(), UserId: server.NewId(), ClientId: server.NewId(), DeviceId: server.NewId(), BalanceId: server.NewId(), State: "active", Deadline: now.Add(lifetime)}
			name := "probe-" + owner.NetworkId.String()
			// Machine accounts use the normal seedphrase hash, not a retained root
			// secret. No public signup/rate-limit or second transaction is involved.
			entropy, err := bip39.NewEntropy(256)
			server.Raise(err)
			phrase, err := bip39.NewMnemonic(entropy)
			server.Raise(err)
			server.RaisePgResult(tx.Exec(ctx, `INSERT INTO network_user(user_id,user_name,auth_type) VALUES($1,$2,$3)`, owner.UserId, name, AuthTypeSeedphrase))
			server.Raise(CreateSeedphraseAuthInTx(tx, ctx, owner.UserId, phrase))
			server.RaisePgResult(tx.Exec(ctx, `INSERT INTO network(network_id,network_name,admin_user_id) VALUES($1,$2,$3)`, owner.NetworkId, name, owner.UserId))
			server.RaisePgResult(tx.Exec(ctx, `INSERT INTO device(device_id,network_id,device_name,device_spec) VALUES($1,$2,$3,$4)`, owner.DeviceId, owner.NetworkId, ProberClientDescription, ProberClientDeviceSpec))
			server.RaisePgResult(tx.Exec(ctx, `INSERT INTO network_client(client_id,network_id,device_id,description,create_time,auth_time) VALUES($1,$2,$3,$4,$5,$5)`, owner.ClientId, owner.NetworkId, owner.DeviceId, ProberClientDescription, now))
			server.RaisePgResult(tx.Exec(ctx, `INSERT INTO transfer_balance(balance_id,network_id,start_time,end_time,start_balance_byte_count,balance_byte_count,net_revenue_nano_cents,subsidy_net_revenue_nano_cents,pro) VALUES($1,$2,$3,$4,$5,$5,0,0,false)`, owner.BalanceId, owner.NetworkId, now, owner.Deadline.Add(24*time.Hour), credit))
			server.RaisePgResult(tx.Exec(ctx, `INSERT INTO prober_shard_run(task_id,epoch,shard_index,shard_count,network_id,user_id,client_id,device_id,balance_id,state,create_time,deadline,next_cleanup_time) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$9,'active',$10,$11,$11)`, key.TaskId, key.Epoch, key.ShardIndex, key.ShardCount, owner.NetworkId, owner.UserId, owner.ClientId, owner.DeviceId, owner.BalanceId, now, owner.Deadline))
		}, server.TxReadCommitted, server.OptNoRetry())
		if returnErr != nil {
			return nil, returnErr
		}
		return owner, nil
	}, func(err error) (*ProberShardOwner, error) { return nil, err })
}

// ProberShardIdentity returns a runtime credential only for this active epoch.
// It never creates a replacement client or stores a JWT in task arguments.
func ProberShardIdentity(ctx context.Context, owner *ProberShardOwner) (*ProberIdentity, error) {
	if owner == nil {
		return nil, ErrProberShardRetired
	}
	return server.HandleError2(func() (*ProberIdentity, error) {
		var name string
		server.Db(ctx, func(conn server.PgConn) {
			server.Raise(conn.QueryRow(ctx, `SELECT n.network_name FROM prober_shard_run r JOIN network n USING(network_id) JOIN network_client c ON c.client_id=r.client_id AND c.network_id=r.network_id WHERE r.task_id=$1 AND r.epoch=$2 AND r.state='active' AND clock_timestamp() AT TIME ZONE 'UTC'<r.deadline AND c.active`, owner.Key.TaskId, owner.Key.Epoch).Scan(&name))
		})
		token, mintErr := session.SignInternalProbe(ctx, session.NewByJwt(owner.NetworkId, owner.UserId, name, false, false).Client(owner.DeviceId, owner.ClientId))
		if mintErr != nil {
			return nil, mintErr
		}
		return &ProberIdentity{NetworkId: &owner.NetworkId, UserId: &owner.UserId, ClientId: &owner.ClientId, NetworkName: name, ByClientJwt: token}, nil
	}, func(err error) (*ProberIdentity, error) {
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, ErrProberShardRetired
		}
		return nil, err
	})
}

// Client creation holds a shared ownership lock until its INSERT commits.
// Draining takes the exclusive lock before enumerating/deactivating clients,
// so a late derived-client callback cannot escape the teardown cohort.
func lockProberShardClientAdmissionInTx(ctx context.Context, tx server.PgTx, networkId server.Id) error {
	_, err := lockProberShardClientAdmissionDeadlineInTx(ctx, tx, networkId)
	return err
}

// Keep the registry lock first, but carry its immutable deadline across later
// endpoint waits. Projecting a clock inside a locking SELECT can precede the
// lock wait, so even this first check reads the clock after acquiring the row.
func lockProberShardClientAdmissionDeadlineInTx(ctx context.Context, tx server.PgTx, networkId server.Id) (*time.Time, error) {
	var state string
	var deadline time.Time
	var admissionDeadline *time.Time
	rows, err := tx.Query(ctx, `SELECT state, deadline FROM prober_shard_run WHERE network_id=$1 FOR SHARE`, networkId)
	// Only the retired-shard policy refusal returns normally. Operational
	// failures must unwind the enclosing void Tx callback: otherwise it reaches
	// COMMIT after a failed admission read and can mask cancellation with a
	// statement-cache/closed-connection error, or commit earlier caller writes.
	server.Raise(err)
	defer rows.Close()
	if rows.Next() {
		server.Raise(rows.Scan(&state, &deadline))
		if state != "active" {
			return nil, ErrProberShardRetired
		}
		admissionDeadline = &deadline
	}
	rows.Close()
	server.Raise(rows.Err())
	return admissionDeadline, validateProberShardAdmissionDeadlineInTx(ctx, tx, admissionDeadline)
}

// A private probe account may fund only contracts in which it is an endpoint;
// two different shard accounts never share a contract or payer. Lock ownership
// before grants or clients: drain locks the registry, clients, then its grant.
// The shared registry fence prevents an admission waiting on a grant from
// deadlocking with drain after it moves on to its endpoint lifecycle locks.
func validateProberShardPayerInTx(ctx context.Context, tx server.PgTx, source, destination, payer server.Id) (*time.Time, error) {
	defer server.EnterContractCreationStage(ctx, server.ContractStageShardFence)()
	rows, err := tx.Query(ctx, `SELECT network_id, state, deadline FROM prober_shard_run
		WHERE network_id=ANY($1) ORDER BY network_id FOR SHARE`, []server.Id{source, destination, payer})
	// Only policy refusals return normally. Database failures must unwind Tx;
	// otherwise its void callback appears successful and a later COMMIT masks
	// the original query/cancellation error with a closed-connection failure.
	server.Raise(err)
	defer rows.Close()
	var admissionDeadline *time.Time
	for rows.Next() {
		var network server.Id
		var state string
		var deadline time.Time
		server.Raise(rows.Scan(&network, &state, &deadline))
		if state != "active" || payer != network || (source != network && destination != network) {
			rows.Close()
			return nil, errors.New("contract is outside its probe shard payer")
		}
		if admissionDeadline == nil || deadline.Before(*admissionDeadline) {
			admissionDeadline = &deadline
		}
	}
	rows.Close()
	server.Raise(rows.Err())
	// A timestamp projected inside the locking SELECT can precede a row-lock
	// wait. Read the database clock only after every selected lock is acquired.
	return admissionDeadline, validateProberShardAdmissionDeadlineInTx(ctx, tx, admissionDeadline)
}

// Registry locks fence state changes, not the passage of time. Admission must
// recheck after any grant/census/client wait and before its financial writes.
func validateProberShardAdmissionDeadlineInTx(ctx context.Context, tx server.PgTx, deadline *time.Time) error {
	if deadline == nil {
		return nil
	}
	var live bool
	server.Raise(tx.QueryRow(ctx, `SELECT clock_timestamp() AT TIME ZONE 'UTC' < $1::timestamp`, *deadline).Scan(&live))
	if !live {
		return ErrProberShardRetired
	}
	return nil
}

// Caller owns the registry row FOR UPDATE. The existing sorted client locks
// serialize with CreateContract's FOR SHARE admission boundary.
func drainProberShardInTx(ctx context.Context, tx server.PgTx, owner *ProberShardOwner) error {
	if owner.State != "active" {
		return nil
	}
	admitted, err := tryTransferBalanceOwnershipInTx(ctx, tx, []server.Id{owner.BalanceId})
	if err != nil {
		return err
	}
	if !admitted {
		return errTransferBalanceOwnershipBusy
	}
	var clients []server.Id
	// The registry fence prevents new shard admissions. Already retired clients
	// need no second timestamp or index rewrite; lock the remaining live set in
	// the same order as ordinary deactivation before reading its common clock.
	rows, err := tx.Query(ctx, `SELECT client_id FROM network_client
		WHERE network_id=$1 AND active=true ORDER BY client_id FOR UPDATE`, owner.NetworkId)
	if err != nil {
		return err
	}
	for rows.Next() {
		var id server.Id
		if err = rows.Scan(&id); err != nil {
			rows.Close()
			return err
		}
		clients = append(clients, id)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	if _, err = deactivateLockedNetworkClientsInTx(ctx, tx, clients, owner.NetworkId); err != nil {
		return err
	}
	// active is a generated amount predicate. Expire admission without changing
	// consumed credit or the settlement principal still needed by open escrow.
	if _, err = tx.Exec(ctx, `UPDATE transfer_balance SET end_time=LEAST(end_time,clock_timestamp() AT TIME ZONE 'UTC') WHERE balance_id=$1 AND network_id=$2`, owner.BalanceId, owner.NetworkId); err != nil {
		return err
	}
	_, err = tx.Exec(ctx, `UPDATE prober_shard_run SET state='draining',next_cleanup_time=clock_timestamp() AT TIME ZONE 'UTC' WHERE task_id=$1 AND epoch=$2 AND state<>'closed'`, owner.Key.TaskId, owner.Key.Epoch)
	return err
}

func DrainProberShard(ctx context.Context, key ProberShardKey) error {
	_, err := server.HandleError2(func() (struct{}, error) {
		server.Tx(ctx, func(tx server.PgTx) {
			owner, err := scanProberShard(tx.QueryRow(ctx, `SELECT `+proberShardColumns+` FROM prober_shard_run WHERE task_id=$1 AND epoch=$2 FOR UPDATE`, key.TaskId, key.Epoch))
			server.Raise(err)
			if owner.Key != key {
				server.Raise(fmt.Errorf("probe shard owner mismatch"))
			}
			server.Raise(drainProberShardInTx(ctx, tx, owner))
		}, server.TxReadCommitted, server.OptNoRetry())
		return struct{}{}, nil
	}, func(err error) (struct{}, error) { return struct{}{}, err })
	return err
}

// The contracts of one shard payer that have no outcome, read through the two
// partial indexes that hold exactly such contracts. The generated open column
// is dispute = false AND outcome IS NULL, so they are the union of:
//   - the payer's undisputed ones, a range of the unresolved-payer index
//     (transfer_contract_unresolved_payer_transfer_byte_count), keyed by payer;
//   - the payer's disputed ones, which the dispute index
//     (transfer_contract_dispute_partial_create_time) holds among the few open
//     disputes of every payer.
//
// Neither index holds a contract once it has an outcome, so the work is the
// payer's unresolved contracts, not its whole history: a drained shard whose
// contracts all settled reads nothing. The full payer index was removed, and
// the reads no longer need (open,payer_network_id,transfer_byte_count) either.
// The first arm repeats its partial index's predicate and never names outcome
// bare, so the global outcome index cannot replace the payer range even when
// its statistics read a false zero. Each arm keeps its own plan behind OFFSET
// 0. Disputed unresolved and unanchored zero-byte contracts still block
// deletion.
const proberShardPayerContractScopeSql = `
	CROSS JOIN LATERAL (
		(
			SELECT contract_id, outcome
			FROM transfer_contract
			WHERE
				(CASE WHEN outcome IS NULL THEN dispute = false ELSE false END) AND
				payer_network_id = payer_scope.network_id
			OFFSET 0
		)
		UNION ALL
		(
			SELECT contract_id, outcome
			FROM transfer_contract
			WHERE
				dispute AND outcome IS NULL AND
				payer_network_id = payer_scope.network_id
			OFFSET 0
		)
	) AS scoped_contract
`

const proberShardReportedContractsSql = `
	SELECT scoped_contract.contract_id
	FROM (
		SELECT network_id FROM prober_shard_run
		WHERE task_id=$1 AND epoch=$2 AND state='draining'
	) AS payer_scope
` + proberShardPayerContractScopeSql + `
	CROSS JOIN LATERAL (
		SELECT 1 FROM contract_close
		WHERE contract_id=scoped_contract.contract_id AND party=$3 AND NOT checkpoint
		LIMIT 1 OFFSET 0
	) AS source_final
	CROSS JOIN LATERAL (
		SELECT 1 FROM contract_close
		WHERE contract_id=scoped_contract.contract_id AND party=$4 AND NOT checkpoint
		LIMIT 1 OFFSET 0
	) AS destination_final
	WHERE scoped_contract.outcome IS NULL
	ORDER BY scoped_contract.contract_id LIMIT 32
`

const proberShardHasUnresolvedContractsSql = `
	SELECT EXISTS (
		SELECT 1 FROM (SELECT $1::uuid AS network_id) AS payer_scope
` + proberShardPayerContractScopeSql + `
		WHERE scoped_contract.outcome IS NULL
	)
`

// Retry only contracts whose two actual final reports already authorize normal
// settlement. This runs without an ownership/balance lock: settlement keeps its
// existing contract-before-balance lock order. Missing/checkpoint reports and
// terminal-but-unsettled accounting remain debt, never invented zero usage.
func settleReportedProberShardContracts(ctx context.Context, key ProberShardKey) error {
	var contracts []server.Id
	server.Db(ctx, func(conn server.PgConn) {
		rows, err := conn.Query(ctx, proberShardReportedContractsSql,
			key.TaskId, key.Epoch, ContractPartySource, ContractPartyDestination)
		server.WithPgResult(rows, err, func() {
			for rows.Next() {
				var id server.Id
				server.Raise(rows.Scan(&id))
				contracts = append(contracts, id)
			}
		})
	})
	for _, id := range contracts {
		closed, err := settleContract(ctx, id)
		if err != nil {
			return err
		}
		if closed {
			RemoveFromStream(ctx, id)
		}
	}
	return nil
}

// Why reapProberShard left a shard in place. Each clears by itself, by the
// contract expiry or by an operator; the shard stays registered meanwhile.
const (
	// the shard is still live: it is drained first
	proberShardReapBlockedActive = "active"
	// a contract it funded has no outcome
	proberShardReapBlockedUnresolved = "unresolved"
	// an escrow of a balance of its network is not settled, or a debit of one
	// is still journaled
	proberShardReapBlockedUnsettled = "unsettled"
	// its network holds a balance that is not a plain grant, or one that
	// arrived after the ownership probe
	proberShardReapBlockedBalance = "balance"
	// a client of its network owns a hosted proxy resource
	proberShardReapBlockedHosted = "hosted"
	// a client of its network is connected
	proberShardReapBlockedConnected = "connected"
)

var proberShardReapBlockReasons = []string{
	proberShardReapBlockedActive,
	proberShardReapBlockedUnresolved,
	proberShardReapBlockedUnsettled,
	proberShardReapBlockedBalance,
	proberShardReapBlockedHosted,
	proberShardReapBlockedConnected,
}

// What one reapProberShard did.
type proberShardReap struct {
	// the shard is closed: its identity is gone and its cache cleared
	closed bool
	// why the shard was left in place; empty once it closed
	blocked string
	// rows its identity transaction deleted, by table
	deleted map[string]int64
}

// ReapProberShard never guesses usage or erases an unsettled financial row. A
// blocked owner stays durably draining and is retried by the recurring task.
// It deletes the shard's identity now, whatever its generation: the retention
// (RemoveProberShardGenerations) calls it once the generation drops.
func ReapProberShard(ctx context.Context, key ProberShardKey) (deleted bool, returnErr error) {
	reap, err := reapProberShard(ctx, key)
	if err != nil {
		return false, err
	}
	return reap.closed, nil
}

func reapProberShard(ctx context.Context, key ProberShardKey) (*proberShardReap, error) {
	return server.HandleError2(func() (*proberShardReap, error) {
		// Persist retry progress before settlement or Redis work can fail. A
		// broken owner must not monopolize the next bounded cleanup page. The
		// stamp never moves a retry earlier: the retention has postponed the
		// pass it is dropping past its run's clock, and a run's later page
		// must not take the pass up again while this one still works on it.
		server.Tx(ctx, func(tx server.PgTx) {
			server.RaisePgResult(tx.Exec(ctx, `UPDATE prober_shard_run
				SET next_cleanup_time=GREATEST(next_cleanup_time,(clock_timestamp() AT TIME ZONE 'UTC')+interval '1 minute')
				WHERE task_id=$1 AND epoch=$2 AND state IN ('draining','deleted')`, key.TaskId, key.Epoch))
		}, server.TxReadCommitted, server.OptNoRetry())
		if err := settleReportedProberShardContracts(ctx, key); err != nil {
			return nil, err
		}
		var reap *proberShardReap
		var cacheOwner *ProberShardOwner
		// the balances the delete removed, for their net escrow mirrors; a
		// resumed cleanup knows only the shard's own credit
		var retiredBalanceIds []server.Id
		server.Tx(ctx, func(tx server.PgTx) {
			// a retried attempt starts over
			reap = &proberShardReap{deleted: map[string]int64{}}
			cacheOwner = nil
			retiredBalanceIds = nil
			owner, err := scanProberShard(tx.QueryRow(ctx, `SELECT `+proberShardColumns+` FROM prober_shard_run WHERE task_id=$1 AND epoch=$2 FOR UPDATE`, key.TaskId, key.Epoch))
			server.Raise(err)
			if owner.Key != key {
				server.Raise(errors.New("probe shard owner mismatch"))
			}
			if owner.State == "closed" {
				reap.closed = true
				return
			}
			if owner.State == "deleted" {
				cacheOwner = owner
				return
			}
			if owner.State != "draining" {
				reap.blocked = proberShardReapBlockedActive
				return
			}
			// The private network's balances: the shard's own credit, and any
			// grant a writer added to the network, such as the daily free grant
			// before it skipped prober networks. Read their ids before the one
			// ownership probe, which must name every key the delete will hold.
			balanceIds := []server.Id{owner.BalanceId}
			rows, err := tx.Query(ctx, `SELECT balance_id FROM transfer_balance WHERE network_id=$1`, owner.NetworkId)
			server.WithPgResult(rows, err, func() {
				for rows.Next() {
					var id server.Id
					server.Raise(rows.Scan(&id))
					balanceIds = append(balanceIds, id)
				}
			})
			slices.SortFunc(balanceIds, func(a, b server.Id) int { return a.Cmp(b) })
			balanceIds = slices.Compact(balanceIds)
			admitted, ownershipErr := tryTransferBalanceOwnershipInTx(ctx, tx, ownableTransferBalanceIds(balanceIds))
			server.Raise(ownershipErr)
			if !admitted {
				server.Raise(errTransferBalanceOwnershipBusy)
			}
			// Registry precedes the compatibility bridge; grants and client
			// teardown follow it, matching normal authenticated admission.
			server.RaisePgResult(tx.Exec(ctx, `SELECT pg_advisory_xact_lock_shared(-776::bigint)`))
			// Settlement takes a contract lock before the balance lock. This read
			// never locks contracts while holding a balance: its post-lock snapshot
			// either sees a completed debit or retains the open/unsettled debt.
			// Every balance of the network is locked, in id order. The shard's
			// own credit must be there and plain. Another balance goes with the
			// network only when it is a plain grant too (no payment, no Pro, no
			// revenue), owned above; one that is not, or that arrived after the
			// ownership probe, keeps the shard draining for an operator.
			var ownFound, ownPlain bool
			othersPlain := true
			lockedBalanceIds := []server.Id{}
			rows, err = tx.Query(ctx, `SELECT balance_id, NOT paid AND NOT pro AND net_revenue_nano_cents=0 AND subsidy_net_revenue_nano_cents=0
				FROM transfer_balance WHERE network_id=$1 ORDER BY balance_id FOR UPDATE`, owner.NetworkId)
			server.WithPgResult(rows, err, func() {
				for rows.Next() {
					var id server.Id
					var plain bool
					server.Raise(rows.Scan(&id, &plain))
					lockedBalanceIds = append(lockedBalanceIds, id)
					if id == owner.BalanceId {
						ownFound, ownPlain = true, plain
					} else if !plain || !slices.Contains(balanceIds, id) {
						othersPlain = false
					}
				}
			})
			if !ownFound || !ownPlain {
				server.Raise(errors.New("probe shard funding record is missing or changed"))
			}
			if !othersPlain {
				reap.blocked = proberShardReapBlockedBalance
				return
			}
			var blocked bool
			server.Raise(tx.QueryRow(ctx, `SELECT
				EXISTS (SELECT 1 FROM transfer_escrow WHERE balance_id=ANY($1) AND NOT settled) OR
				EXISTS (SELECT 1 FROM transfer_debit_journal WHERE balance_id=ANY($1))`, lockedBalanceIds).Scan(&blocked))
			if blocked {
				reap.blocked = proberShardReapBlockedUnsettled
				return
			}
			server.Raise(tx.QueryRow(ctx, proberShardHasUnresolvedContractsSql, owner.NetworkId).Scan(&blocked))
			if blocked {
				reap.blocked = proberShardReapBlockedUnresolved
				return
			}
			// Probe tunnels create ordinary clients, not hosted proxy devices.
			// Preserve any unexpected hosted resource for explicit cleanup rather
			// than deleting its credential owner underneath an active proxy.
			server.Raise(tx.QueryRow(ctx, `SELECT EXISTS (
				SELECT 1 FROM network_client c JOIN proxy_device_config p USING(client_id)
				WHERE c.network_id=$1
			) OR EXISTS (
				SELECT 1 FROM network_client c JOIN proxy_client p USING(client_id)
				WHERE c.network_id=$1
			)`, owner.NetworkId).Scan(&blocked))
			if blocked {
				reap.blocked = proberShardReapBlockedHosted
				return
			}
			// validateProberShardPayerInTx requires this payer for every private
			// contract (including zero-byte/companions) and rejects no-payer
			// creation. The indexed payer test above therefore covers the whole
			// owner without one history scan per transient child client.
			// The owning tunnel must disconnect before its identity is removed.
			server.Raise(tx.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM network_client c JOIN network_client_connection x USING(client_id) WHERE c.network_id=$1 AND x.connected)`, owner.NetworkId).Scan(&blocked))
			if blocked {
				reap.blocked = proberShardReapBlockedConnected
				return
			}
			clients := []server.Id{owner.ClientId}
			rows, err = tx.Query(ctx, `SELECT client_id FROM network_client WHERE network_id=$1 ORDER BY client_id`, owner.NetworkId)
			server.WithPgResult(rows, err, func() {
				for rows.Next() {
					var id server.Id
					server.Raise(rows.Scan(&id))
					clients = append(clients, id)
				}
			})
			slices.SortFunc(clients, func(a, b server.Id) int { return a.Cmp(b) })
			clients = slices.Compact(clients)
			providerWorkLockCurrentSessionMutationInTx(ctx, tx, clients...)
			server.Raise(tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM network_client_connection WHERE client_id=ANY($1) AND connected)`, clients).Scan(&blocked))
			if blocked {
				reap.blocked = proberShardReapBlockedConnected
				return
			}
			// The durable post-delete record retains this cohort if Redis is down
			// or the worker exits after the SQL commit. No identity can be reminted
			// once the owner leaves active, and client UUIDs are never reused.
			owner.RetiredClientIds = clients
			deleted := func(table string, tag pgconn.CommandTag) {
				reap.deleted[table] += tag.RowsAffected()
			}
			// These accounts only own their one device and authentication record.
			// Financial contracts, sweeps, signed history and balance revision
			// tombstones deliberately outlive the disposable account.
			deleted("client_tls_certificate", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM client_tls_certificate WHERE client_id=ANY($1)`, clients)))
			deleted("network_client_role", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM network_client_role WHERE client_id=ANY($1)`, clients)))
			deleted("network_client_connection", server.RaisePgResult(tx.Exec(ctx, `WITH connections AS MATERIALIZED (
				SELECT connection_id FROM network_client_connection WHERE client_id=ANY($1)
			), locations AS (DELETE FROM network_client_location WHERE connection_id IN (SELECT connection_id FROM connections)),
			latencies AS (DELETE FROM network_client_latency WHERE connection_id IN (SELECT connection_id FROM connections)),
			speeds AS (DELETE FROM network_client_speed WHERE connection_id IN (SELECT connection_id FROM connections))
			DELETE FROM network_client_connection WHERE client_id=ANY($1)`, clients)))
			deleted("provide_key", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM provide_key WHERE client_id=ANY($1)`, clients)))
			// A connected client gets a location reliability row, and the
			// ordinary client reap leaves it to the row's 31-day expiry. A probe
			// client never provides, so nothing reads its row once it is gone.
			deleted("network_client_location_reliability", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM network_client_location_reliability WHERE client_id=ANY($1)`, clients)))
			deleted("network_client_provider_intent", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM network_client_provider_intent WHERE client_id=ANY($1)`, clients)))
			// every revocation record of the network refuses its clients
			// before the deletion commits
			server.Raise(session.RetireNetworkRecords(ctx, owner.NetworkId))
			deleted("network_client", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM network_client WHERE network_id=$1`, owner.NetworkId)))
			deleted("device", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM device WHERE network_id=$1`, owner.NetworkId)))
			deleted("transfer_balance", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM transfer_balance WHERE balance_id=ANY($1) AND network_id=$2`, lockedBalanceIds, owner.NetworkId)))
			retiredBalanceIds = lockedBalanceIds
			deleted("network", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM network WHERE network_id=$1 AND admin_user_id=$2`, owner.NetworkId, owner.UserId)))
			deleted("network_user_auth_seedphrase", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM network_user_auth_seedphrase WHERE user_id=$1`, owner.UserId)))
			deleted("network_user", server.RaisePgResult(tx.Exec(ctx, `DELETE FROM network_user WHERE user_id=$1`, owner.UserId)))
			server.RaisePgResult(tx.Exec(ctx, `UPDATE prober_shard_run SET state='deleted',retired_client_ids=$3,close_time=clock_timestamp() AT TIME ZONE 'UTC' WHERE task_id=$1 AND epoch=$2`, key.TaskId, key.Epoch, clients))
			cacheOwner = owner
		}, server.TxReadCommitted, server.OptNoRetry())
		if cacheOwner != nil {
			// Ordinary model cleanup uses bounded cross-slot pipelines. Keep all
			// Redis I/O outside the transaction and repeat safely after a crash.
			removeReapedClientRedisState(ctx, cacheOwner.RetiredClientIds)
			forEachReapedClientRedisChunk(cacheOwner.RetiredClientIds, func(ids []server.Id) {
				server.Redis(ctx, func(r server.RedisClient) {
					_, err := r.Pipelined(ctx, func(pipe redis.Pipeliner) error {
						for _, id := range ids {
							pipe.Del(ctx, residentKey(id))
							pipe.Del(ctx, provideModesKey(id))
							for mode := ProvideModeDefault; mode <= ProvideModeStream; mode++ {
								pipe.Del(ctx, provideModeSecretKeyKey(id, mode))
							}
						}
						return nil
					})
					server.Raise(err)
				})
			})
			if !slices.Contains(retiredBalanceIds, cacheOwner.BalanceId) {
				retiredBalanceIds = append(retiredBalanceIds, cacheOwner.BalanceId)
			}
			refreshNetEscrow(ctx, retiredBalanceIds)
			server.Tx(ctx, func(tx server.PgTx) {
				server.RaisePgResult(tx.Exec(ctx, `UPDATE prober_shard_run SET state='closed',retired_client_ids='{}' WHERE task_id=$1 AND epoch=$2 AND state='deleted'`, key.TaskId, key.Epoch))
			}, server.TxReadCommitted, server.OptNoRetry())
			reap.closed = true
		}
		return reap, nil
	}, func(err error) (*proberShardReap, error) { return nil, err })
}

// SettleProberShard ends a pass's cleanup without deleting anything. It
// retries the normal settlement of the shard's contracts whose two final
// reports exist. Once none of its contracts lacks an outcome and no escrow of
// its network's balances is unsettled, the shard is settled: it waits, with
// next_cleanup_time 'infinity', for its generation to drop
// (RemoveProberShardGenerations). Otherwise it is due again a minute later. A
// changed funding record is an error, as it is for ReapProberShard.
func SettleProberShard(ctx context.Context, key ProberShardKey) error {
	_, err := server.HandleError2(func() (struct{}, error) {
		server.Tx(ctx, func(tx server.PgTx) {
			server.RaisePgResult(tx.Exec(ctx, `UPDATE prober_shard_run
				SET next_cleanup_time=(clock_timestamp() AT TIME ZONE 'UTC')+interval '1 minute'
				WHERE task_id=$1 AND epoch=$2 AND state='draining'`, key.TaskId, key.Epoch))
		}, server.TxReadCommitted, server.OptNoRetry())
		if err := settleReportedProberShardContracts(ctx, key); err != nil {
			return struct{}{}, err
		}
		server.Tx(ctx, func(tx server.PgTx) {
			owner, err := scanProberShard(tx.QueryRow(ctx, `SELECT `+proberShardColumns+` FROM prober_shard_run WHERE task_id=$1 AND epoch=$2 FOR UPDATE`, key.TaskId, key.Epoch))
			server.Raise(err)
			if owner.Key != key {
				server.Raise(errors.New("probe shard owner mismatch"))
			}
			if owner.State != "draining" {
				return
			}
			var found, plain bool
			rows, err := tx.Query(ctx, `SELECT NOT paid AND NOT pro AND net_revenue_nano_cents=0 AND subsidy_net_revenue_nano_cents=0 FROM transfer_balance WHERE balance_id=$1 AND network_id=$2`, owner.BalanceId, owner.NetworkId)
			server.WithPgResult(rows, err, func() {
				if rows.Next() {
					server.Raise(rows.Scan(&plain))
					found = true
				}
			})
			if !found || !plain {
				server.Raise(errors.New("probe shard funding record is missing or changed"))
			}
			var unsettled bool
			server.Raise(tx.QueryRow(ctx, proberShardHasUnresolvedContractsSql, owner.NetworkId).Scan(&unsettled))
			if !unsettled {
				server.Raise(tx.QueryRow(ctx, `SELECT EXISTS (
					SELECT 1 FROM transfer_balance AS balance
					CROSS JOIN LATERAL (
						SELECT 1 FROM transfer_escrow
						WHERE transfer_escrow.balance_id = balance.balance_id AND NOT transfer_escrow.settled
						LIMIT 1
					) AS escrow
					WHERE balance.network_id = $1
				)`, owner.NetworkId).Scan(&unsettled))
			}
			if unsettled {
				return
			}
			server.RaisePgResult(tx.Exec(ctx, `UPDATE prober_shard_run SET next_cleanup_time='infinity' WHERE task_id=$1 AND epoch=$2 AND state='draining'`, key.TaskId, key.Epoch))
		}, server.TxReadCommitted, server.OptNoRetry())
		return struct{}{}, nil
	}, func(err error) (struct{}, error) { return struct{}{}, err })
	return err
}

// One bounded pass over the shards due for a step that deletes nothing. A live
// pass past its deadline, in any generation, is drained: a crashed or expired
// execution's identity is fenced. A drained pass of a kept generation settles
// (SettleProberShard). A drained pass of a dropped generation is the
// retention's (RemoveProberShardGenerations). Each owner's durable timestamp
// advances before its steps, so one failure cannot hold the next page.
func SettleDueProberShards(ctx context.Context, limit int) (int, error) {
	if limit < 1 || limit > 256 {
		return 0, errors.New("invalid probe shard cleanup limit")
	}
	settings := DefaultProberShardRetentionSettings()
	cutoff := ProberShardRetentionCutoff(server.NowUtc(), settings.GenerationDuration, proberShardRetainedGenerations(ctx, settings))
	return server.HandleError2(func() (int, error) {
		var owners []*ProberShardOwner
		server.Tx(ctx, func(tx server.PgTx) {
			owners = nil
			rows, err := tx.Query(ctx, `SELECT `+proberShardColumns+` FROM prober_shard_run
				WHERE state<>'closed' AND next_cleanup_time<=clock_timestamp() AT TIME ZONE 'UTC' AND (state='active' OR create_time>=$2)
				ORDER BY next_cleanup_time,task_id,epoch LIMIT $1 FOR UPDATE SKIP LOCKED`, limit, cutoff)
			server.WithPgResult(rows, err, func() {
				for rows.Next() {
					owner, err := scanProberShard(rows)
					server.Raise(err)
					owners = append(owners, owner)
				}
			})
			server.BatchInTx(ctx, tx, func(batch server.PgBatch) {
				for _, owner := range owners {
					batch.Queue(`UPDATE prober_shard_run SET next_cleanup_time=(clock_timestamp() AT TIME ZONE 'UTC')+interval '1 minute' WHERE task_id=$1 AND epoch=$2`, owner.Key.TaskId, owner.Key.Epoch)
				}
			})
		}, server.TxReadCommitted, server.OptNoRetry())
		done := 0
		var cleanupErr error
		for _, owner := range owners {
			if err := ctx.Err(); err != nil {
				return done, err
			}
			if err := DrainProberShard(ctx, owner.Key); err != nil {
				cleanupErr = errors.Join(cleanupErr, err)
				continue
			}
			if owner.State == "deleted" {
				// an identity delete committed before its cache cleanup failed:
				// finish it, deleting nothing more
				if _, err := ReapProberShard(ctx, owner.Key); err != nil {
					cleanupErr = errors.Join(cleanupErr, err)
					continue
				}
			} else if err := SettleProberShard(ctx, owner.Key); err != nil {
				cleanupErr = errors.Join(cleanupErr, err)
				continue
			}
			done++
		}
		return done, cleanupErr
	}, func(err error) (int, error) { return 0, err })
}
