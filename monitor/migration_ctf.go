// The columns every capture the flag table leads with.
func ctfMigrationKeyColumns(epoch bool) []snMainnetMigrationColumn {
	columns := []snMainnetMigrationColumn{
		{name: "deployment_key", kind: "character varying(96)", notNull: true},
		{name: "no_id", kind: "bigint", notNull: true},
	}
	if epoch {
		columns = append(columns, snMainnetMigrationColumn{name: "epoch", kind: "bigint", notNull: true})
	}
	return columns
}

func ctfMigrationColumns(table string, epoch bool, columns ...snMainnetMigrationColumn) string {
	return snMainnetMigrationColumns(table, append(ctfMigrationKeyColumns(epoch), columns...)...)
}

